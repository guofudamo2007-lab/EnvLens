export type Key = keyof typeof words
export type Translator = (key: Key) => string
const translations: Record<Lang, Translator> = {
  zh: (key) => words[key][0],
  en: (key) => words[key][1],
}
export function translator(lang: Lang): Translator {
  return translations[lang]
}
export function errorKey(error: unknown): Key {
  return typeof error === 'string' && error in words ? (error as Key) : 'internal'
}
